let cache = null;

/** 기본 도서 목록을 돌려준다. (실제 도서관 목록으로 바꿀 때 이 함수의 안쪽만 바꾼다.) */
export async function loadBaseBooks(/* env */) {
  if (!cache) {
    cache = SAMPLE_BOOKS.map(([title, author, cat], i) => ({
      id: 'b' + String(i + 1).padStart(2, '0'),
      title,
      author,
      category: CATEGORIES[cat],
    }));
  }
  return cache;
}
